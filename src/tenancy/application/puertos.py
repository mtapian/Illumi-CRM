"""Puertos que tenancy necesita de su infraestructura."""

from datetime import date
from decimal import Decimal
from typing import Protocol

from tenancy.domain.habilitaciones import Ajuste
from tenancy.domain.permisos import Rol
from tenancy.domain.suscripcion import Estado


class ParametrosRepo(Protocol):
    def historial(self, clave: str, empresa_id: int | None) -> list[tuple[date, Decimal]]: ...
    def agregar(self, clave: str, empresa_id: int | None, valor: Decimal, desde: date) -> None: ...


class EmpresasRepo(Protocol):
    def estado(self, empresa_id: int) -> tuple[Estado, date | None]: ...
    def actualizar(self, empresa_id: int, datos: dict) -> None: ...
    def limite_productos(self, empresa_id: int) -> int | None: ...


class RegistroRepo(Protocol):
    def existe_ruc(self, ruc: str) -> bool: ...
    def existe_email(self, email: str) -> bool: ...
    def plan_de_prueba(self) -> tuple[int, int] | None:
        """(plan_id, dias_prueba) del plan de prueba activo."""
        ...

    def crear_empresa(
        self, ruc: str, razon_social: str, nombre_comercial: str, plan_id: int, fecha_termino: date
    ) -> int: ...
    def crear_usuario(self, empresa_id: int, nombre: str, email: str, password: str) -> int: ...


class HabilitacionesRepo(Protocol):
    def funcionalidades_plan(self, empresa_id: int) -> set[str]: ...
    def ajustes(self, empresa_id: int) -> list[Ajuste]:
        """Ajustes no revocados (vigentes o vencidos)."""
        ...


class RolesRepo(Protocol):
    def crear_rol(
        self, empresa_id: int, nombre: str, permisos, es_sistema: bool = False
    ) -> int: ...
    def asignar_roles(self, usuario_id: int, rol_ids: list[int]) -> None:
        """Reemplaza los roles del usuario."""
        ...


class AccesosRepo(RolesRepo, Protocol):
    """Usuarios y roles de una empresa. Toda lectura filtra por `empresa_id`; si el
    registro es de otra empresa lanza `NoEncontrado` (RF-TEN-52)."""

    def bloquear_empresa(self, empresa_id: int) -> int | None:
        """Bloquea la fila de la empresa hasta el commit y devuelve el límite de usuarios."""
        ...

    def contar_activos_no_tecnicos(self, empresa_id: int) -> int: ...
    def existe_email(self, email: str) -> bool: ...
    def crear_usuario(self, empresa_id: int, nombre: str, email: str, password: str) -> int: ...
    def usuario(self, empresa_id: int, usuario_id: int) -> tuple[bool, bool]:
        """(activo, es_tecnico)."""
        ...

    def actualizar_usuario(self, usuario_id: int, **campos) -> None: ...
    def administradores_activos(self, empresa_id: int) -> set[int]: ...
    def roles(self, empresa_id: int, rol_ids) -> list[Rol]: ...
    def rol(self, empresa_id: int, rol_id: int) -> Rol: ...
    def permisos_guardados(self, rol_id: int) -> set[str]: ...
    def actualizar_rol(self, rol_id: int, nombre: str, permisos) -> None: ...
    def cambiar_estado_rol(self, rol_id: int, activo: bool) -> None: ...
    def usuarios_con_rol(self, rol_id: int) -> int: ...
    def eliminar_rol(self, rol_id: int) -> None: ...
    def nombres_roles(self, usuario_id: int) -> list[str]: ...
    def revocar_tokens_de(self, usuario_id: int) -> None: ...
    def usuario_tecnico(self, empresa_id: int, nombre: str) -> int | None: ...
    def crear_usuario_tecnico(self, empresa_id: int, nombre: str) -> int: ...
    def guardar_token(
        self,
        empresa_id: int,
        usuario_id: int,
        nombre: str,
        token_hash: str,
        prefijo: str,
        creado_por: int,
    ) -> int: ...
    def token(self, empresa_id: int, token_id: int) -> tuple[str, bool]:
        """(nombre, revocado); `NoEncontrado` si es de otra empresa."""
        ...

    def revocar_token(self, token_id: int) -> None: ...
    def auditar(
        self,
        empresa_id: int,
        actor_id: int | None,
        entidad: str,
        entidad_id: int,
        accion: str,
        antes: dict | None,
        despues: dict | None,
    ) -> None:
        """Registra un cambio de acceso (RF-TEN-43). Solo inserción."""
        ...
